    private void calculoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calculoActionPerformed
        lblError.setText("");
        lblResult.setText("");
        String t1 = jTextField1.getText().trim();
        String t2 = jTextField2.getText().trim();

        if (t1.isEmpty() || t2.isEmpty()) {
            lblError.setText("Error: no puedes dejar cajas vacías");
            return;
        }
        try {
            double n1 = Double.parseDouble(t1);
            double n2 = Double.parseDouble(t2);
            double suma = n1 + n2;
            lblResult.setText("Resultado: " + suma);
        } catch (NumberFormatException e) {
            lblError.setText("Error: introduce solo números");
        }
    }//GEN-LAST:event_calculoActionPerformed

